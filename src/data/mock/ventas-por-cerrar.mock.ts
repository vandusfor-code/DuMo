export function computeVentasPorCerrarKpis(rows: DuoSale[]) {
  const pendingAssignment = rows.filter((r) => r.status === "pending_assignment").length;
  const assigned = rows.filter((r) => r.status === "assigned").length;
  const noContact = rows.filter(
    (r) => r.status === "assigned" && r.closingNotes.length > 0,
  ).length;
  return { pendingAssignment, assigned, noContact };
}
